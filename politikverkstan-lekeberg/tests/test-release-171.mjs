import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const root=new URL('../',import.meta.url);
const read=name=>readFileSync(new URL(name,root),'utf8');
const calendar=read('../.github/workflows/meetingplus-calendar.yml');
const ci=read('../.github/workflows/politikverkstan-ci.yml');
const promote=read('../.github/workflows/politikverkstan-promote.yml');
assert(calendar.includes('actions: write'),'Calendar workflow needs permission to dispatch CI');
assert(calendar.includes('id: snapshot'),'Calendar changes require a trackable output');
assert(calendar.includes('changed=false')&&calendar.includes('changed=true'),'Must distinguish unchanged snapshots');
assert(calendar.includes("if: steps.snapshot.outputs.changed == 'true'"),'Dispatch only after an actual change');
assert(calendar.includes('gh workflow run politikverkstan-ci.yml --ref main'),'Calendar must trigger full CI');
assert(calendar.indexOf('git push origin HEAD:main')<calendar.indexOf('gh workflow run politikverkstan-ci.yml --ref main'),
 'Dispatch CI only after successful calendar push');
assert(ci.includes('name: Politikverkstan quality')&&ci.includes('workflow_dispatch:'));
assert(ci.includes('Chromium browser regressions')&&ci.includes('Run browser and PDF regressions'));
assert(promote.includes('workflows: ["Politikverkstan quality"]'),'Promoter and CI names must match');
assert(promote.includes("github.event.workflow_run.event == 'workflow_dispatch'"));
assert(promote.includes("github.event.workflow_run.event == 'push'"));
assert(promote.includes("github.event.workflow_run.conclusion == 'success'"));
assert(promote.includes('if [ "$ACTUAL_MAIN" != "$PASSED_SHA" ]'),'Never promote stale CI');
assert(promote.includes('git merge-base --is-ancestor'),'Require fast-forward history');
assert(!promote.includes('git push --force'),'Must not bypass release history');
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.version,'1.7.1');
const ui=read('src/meetings-ui.js'),shell=read('src/workroom.js'),generated=read('worker/workroom-page.mjs');
assert(ui.includes("Date.now()-seen>48*60*60*1000"),'Stale source warning required');
assert(ui.includes('Kalenderuppgifter saknar färsk bekräftelse'));
assert(shell.includes('Version 1.7.1'));
assert(generated.includes('Version 1.7.1'));
assert(generated.includes('Kalenderuppgifter saknar färsk bekräftelse'));
console.log('PASS 1.7.1: scheduled dispatch, tested-head promotion, stale-source warning and version label');
